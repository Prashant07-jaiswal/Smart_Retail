import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import react from '@vitejs/plugin-react';
import { defineConfig, loadEnv } from 'vite';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

// https://vite.dev/config/
export default defineConfig(({ mode }) => {
  const env = loadEnv(mode, process.cwd(), '');

  // HTTPS is required for camera/barcode-scanning access from any device
  // that isn't "localhost" — browsers block getUserMedia on plain
  // http://<ip>. When VITE_USE_HTTPS=true, this reuses the same shared
  // self-signed cert as the backend (generated by scripts/set-network.js).
  // Falls back to plain HTTP automatically if the cert files aren't
  // present, so localhost-only development needs zero extra setup.
  const certPath = path.resolve(__dirname, '..', 'certs', 'cert.pem');
  const keyPath = path.resolve(__dirname, '..', 'certs', 'key.pem');
  const certsExist = fs.existsSync(certPath) && fs.existsSync(keyPath);
  const useHttps = env.VITE_USE_HTTPS === 'true' && certsExist;

  return {
    plugins: [react()],
    server: {
      https: useHttps ? { cert: fs.readFileSync(certPath), key: fs.readFileSync(keyPath) } : undefined,
    },
  };
});
