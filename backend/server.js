require('dotenv').config();
const fs = require('fs');
const path = require('path');
const express = require('express');
const http = require('http');
const https = require('https');
const cors = require('cors');
const { Server } = require('socket.io');

const { setupSocket } = require('./sockets');
const { errorHandler, notFound } = require('./middleware/errorHandler');

const authRoutes = require('./routes/authRoutes');
const productRoutes = require('./routes/productRoutes');
const categoryRoutes = require('./routes/categoryRoutes');
const inventoryRoutes = require('./routes/inventoryRoutes');
const orderRoutes = require('./routes/orderRoutes');
const salesRoutes = require('./routes/salesRoutes');
const dashboardRoutes = require('./routes/dashboardRoutes');
const gemmaChatRoutes = require('./routes/gemmaChatRoutes');

const app = express();

const FRONTEND_URL = process.env.FRONTEND_URL || 'http://localhost:5173';

// HTTPS is required for camera/barcode-scanning access from any device that
// isn't "localhost" (browsers block getUserMedia on plain http://<ip>).
// When USE_HTTPS=true, a shared self-signed cert (generated by
// scripts/set-network.js) is used for the whole stack. Falls back to plain
// HTTP automatically if the cert files aren't present, so local
// localhost-only development keeps working with zero extra setup.
const USE_HTTPS = process.env.USE_HTTPS === 'true';
const CERT_PATH = path.join(__dirname, '..', 'certs', 'cert.pem');
const KEY_PATH = path.join(__dirname, '..', 'certs', 'key.pem');
const certsExist = fs.existsSync(CERT_PATH) && fs.existsSync(KEY_PATH);

let server;
let protocol;
if (USE_HTTPS && certsExist) {
  server = https.createServer(
    { cert: fs.readFileSync(CERT_PATH), key: fs.readFileSync(KEY_PATH) },
    app
  );
  protocol = 'https';
} else {
  if (USE_HTTPS && !certsExist) {
    console.warn('USE_HTTPS=true but certs/cert.pem or certs/key.pem was not found — falling back to plain HTTP.');
    console.warn('Run: node scripts/set-network.js <your-ip>   to generate them.');
  }
  server = http.createServer(app);
  protocol = 'http';
}

const io = new Server(server, {
  cors: { origin: FRONTEND_URL, methods: ['GET', 'POST', 'PUT', 'DELETE'] },
});
setupSocket(io);
app.set('io', io);

app.use(cors({ origin: FRONTEND_URL }));
app.use(express.json());

app.get('/api/health', (req, res) => res.json({ status: 'ok', timestamp: new Date().toISOString() }));

app.use('/api/auth', authRoutes);
app.use('/api/products', productRoutes);
app.use('/api/categories', categoryRoutes);
app.use('/api/inventory', inventoryRoutes);
app.use('/api/orders', orderRoutes);
app.use('/api/sales', salesRoutes);
app.use('/api/dashboard', dashboardRoutes);
app.use('/api/chat', gemmaChatRoutes);

app.use(notFound);
app.use(errorHandler);

const PORT = process.env.PORT || 5000;
server.listen(PORT, () => {
  console.log(`Smart Retail backend running on ${protocol}://localhost:${PORT}`);
  console.log(`Accepting frontend connections from: ${FRONTEND_URL}`);
});

module.exports = { app, server, io };
